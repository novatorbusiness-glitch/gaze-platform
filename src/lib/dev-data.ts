/** ISO-строка в текущем месяце (день 1–28, час 10–18 — безопасно для UTC+3) */
function isoInCurrentMonth(day: number, hour: number): string {
  const now = new Date()
  const y = now.getFullYear()
  const m = String(now.getMonth() + 1).padStart(2, '0')
  const d = String(Math.min(Math.max(day, 1), 28)).padStart(2, '0')
  const h = String(hour).padStart(2, '0')
  return `${y}-${m}-${d}T${h}:00:00Z`
}

/** Дата YYYY-MM-DD: n дней назад от сегодня */
function dateNDaysAgo(n: number): string {
  const d = new Date()
  d.setDate(d.getDate() - n)
  const y = d.getFullYear()
  const m = String(d.getMonth() + 1).padStart(2, '0')
  const day = String(d.getDate()).padStart(2, '0')
  return `${y}-${m}-${day}`
}

