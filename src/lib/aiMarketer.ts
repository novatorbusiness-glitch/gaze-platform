/* ------------------------------------------------------------------ */
/* Генерация: 4 варианта по типу контента                              */
/* ------------------------------------------------------------------ */

export function generateContent(input: AiMarketerInput): GeneratedVariant[] {
  switch (input.type) {
    case 'post':
      return postVariants(input)
    case 'stories':
      return storiesVariants(input)
    case 'offer':
      return offerVariants(input)
    case 'welcome':
      return welcomeVariants(input)
    case 'script':
      return scriptVariants(input)
  }
}

