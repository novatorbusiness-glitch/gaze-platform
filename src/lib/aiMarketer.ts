/** Нормализация ввода: обрезаем, схлопываем пробелы, склоняем в нижний регистр для подстановки */
function norm(s: string): string {
  return s.trim().replace(/\s+/g, ' ')
}

/** Услуга с «контекстом»: если ввод пустой — нейтральное «процедура» */
function serviceText(service: string): string {
  const s = norm(service).toLowerCase()
  return s || 'процедура'
}

/** Боль/аудитория с фолбэком */
function painText(pain: string): string {
  const s = norm(pain)
  return s || 'кому неудобно или некогда ходить в салон'
}

/** Первая буква — заглавная */
function cap(s: string): string {
  return s.charAt(0).toUpperCase() + s.slice(1)
}

/* ------------------------------------------------------------------ */
/* Сборка текста по формуле Нейро-Воронки                               */
/* ------------------------------------------------------------------ */

/** Формула: крючок → боль → решение → оффер → CTA */
function funnel(hook: string, pain: string, solution: string, offer: string, cta: string): string {
  return [hook, pain, solution, offer, cta].join('\n\n')
}

/** Короткая «сторис-версия» формулы: крючок → боль/решение → CTA */
function storiesFunnel(hook: string, body: string, cta: string): string {
  return [hook, body, cta].join('\n\n')
}

