/**
 * GAZE Platform — ПРЕМИУМ-ТАРИФ: AI-МАРКЕТОЛОГ
 *
 * Локальный генератор контента по формуле «Нейро-Воронки» из книги:
 *   Крючок (первая строка цепляет)
 *   → Боль (описывает проблему аудитории)
 *   → Решение (услуга как решение)
 *   → Оффер (что получит клиент)
 *   → CTA (призыв записаться/написать)
 *
 * Детерминированные шаблоны (3-4 варианта на тип) — без внешних вызовов,
 * работает в демо-режиме без API-ключа. Всё подставляется из ввода мастера.
 */

export type ContentType = 'post' | 'stories' | 'offer' | 'welcome' | 'script'
export type Tone = 'friendly' | 'expert' | 'playful'

export interface AiMarketerInput {
  /** Тип контента: Пост / Сторис / Оффер / Приветствие новому клиенту / Скрипт ответа */
  type: ContentType
  /** Услуга мастера, напр. «маникюр» */
  service: string
  /** Боль/аудитория, напр. «клиенткам, которым неудобно ходить в салон» */
  pain: string
  /** Тон: дружелюбный / экспертный / игривый */
  tone: Tone
}

export interface GeneratedVariant {
  /** Короткая подпись варианта («Классика», «История», …) */
  label: string
  /** Готовый текст контента (копируется целиком) */
  text: string
}

/** Карточка-подсказка: чит-код из книги «Нейро-Воронка» */
export interface CheatCard {
  id: string
  category: string
  title: string
  text: string
}

